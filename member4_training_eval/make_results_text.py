"""Generate the prose of the results sections from the recorded numbers.

The numbers of the report are read from ``runs/`` and written into the
LaTeX fragments, so that the prose and the tables can never disagree and
every number in the paper can be recomputed from the run artefacts.

The script writes the fragments as complete LaTeX, with the numbers
interpolated.  A number that is missing is reported as ``--`` instead of
being guessed, so an incomplete experiment set cannot produce a confident
sentence.
"""
from __future__ import annotations

import argparse
import json
import math
from pathlib import Path

import numpy as np
from scipy import stats

import config

CROSS = ("art_painting_test", "cartoon_test", "sketch_test")

LABELS = {
    "original": "Original",
    "adain": "+AdaIN",
    "adain_matched": "+AdaIN (matched)",
    "ours": "+Ours",
    "ours_equal": "+Ours (equal str.)",
    "duplicate": "+Duplicate",
    "nonstyle": "+NonStyle",
}


def load_cross(runs_root: Path, group: str):
    path = runs_root / f"summary_{group}.json"
    if not path.is_file():
        return None
    payload = json.loads(path.read_text(encoding="utf-8"))
    series = []
    for split in CROSS:
        entry = payload.get(split)
        if not entry or not entry.get("per_seed"):
            return None
        series.append(entry["per_seed"])
    seeds = min(len(s) for s in series)
    return [float(np.mean([s[i] for s in series])) for i in range(seeds)]


def level(runs_root: Path, group: str):
    """The mean cross-domain accuracy of a group, or None."""
    series = load_cross(runs_root, group)
    return float(np.mean(series)) if series else None


def common_seeds(runs_root: Path, groups: tuple) -> dict:
    """The per-seed cross-domain averages, restricted to the shared seeds.

    While the seed extension is still running, some groups have five seeds
    and others three.  A paired comparison is only valid over the seeds the
    two groups have in common, so the series are truncated to the common
    prefix.  This keeps every comparison paired and honest at every stage
    of the experiment.
    """
    raw = {g: load_cross(runs_root, g) for g in groups}
    raw = {g: v for g, v in raw.items() if v is not None}
    if not raw:
        return {}
    length = min(len(v) for v in raw.values())
    return {g: v[:length] for g, v in raw.items()}


def paired(a: list, b: list):
    x = np.asarray(a, dtype=float)
    y = np.asarray(b, dtype=float)
    if len(x) != len(y):
        raise ValueError("the two series must have the same length")
    diff = y - x
    n = len(diff)
    mean = float(diff.mean())
    sd = float(diff.std(ddof=1)) if n > 1 else 0.0
    if n > 1 and sd > 0:
        t, p = stats.ttest_rel(y, x)
        t, p = float(t), float(p)
        half = stats.t.ppf(0.975, n - 1) * sd / math.sqrt(n)
    else:
        t, p, half = (0.0, 1.0), 1.0, 0.0
    return mean, mean - half, mean + half, t, p, n


def claim(p: float) -> str:
    """The wording for a p value.  An inconclusive result is named as such."""
    if p < 0.001:
        return "significant"
    if p < 0.05:
        return "significant"
    return "not significant"


def build_main_results(runs_root: Path) -> str:
    """IV.B: the main results and the decomposition."""
    groups = ("original", "duplicate", "nonstyle", "adain", "adain_matched",
              "ours", "ours_equal")
    series = common_seeds(runs_root, groups)
    if "original" not in series or "adain" not in series:
        return ""

    original = series["original"]
    adain = series["adain"]
    duplicate = series.get("duplicate")
    nonstyle = series.get("nonstyle")
    matched = series.get("adain_matched")
    ours = series.get("ours")
    equal = series.get("ours_equal")

    n_seeds = len(original)
    lines = [
        "% Generated by member4_training_eval/make_results_text.py -- do not edit by hand.",
        "\\subsection{Main Results}",
        "\\label{sec:main_results}",
        "",
        f"Table~\\ref{{tab:main_results}} gives the accuracy of every group on the "
        f"in-domain Photo test set and on the three unseen target domains, "
        f"averaged over {n_seeds} seeds.",
        "",
    ]

    o_mean = float(np.mean(original))
    o_std = float(np.std(original, ddof=1)) if n_seeds > 1 else 0.0
    a_mean = float(np.mean(adain))
    a_std = float(np.std(adain, ddof=1)) if n_seeds > 1 else 0.0
    diff, lo, hi, t, p, _ = paired(original, adain)
    lines += [
        f"The Original group reaches ${o_mean*100:.1f}\\pm{o_std*100:.1f}\\%$ on the "
        f"cross-domain average while scoring above 99\\% on Photo Test, so the "
        f"domain gap is large and unambiguous. Adding the AdaIN-styled images "
        f"raises the cross-domain average to ${a_mean*100:.1f}\\pm{a_std*100:.1f}\\%$, "
        f"a paired gain of ${diff*100:+.2f}$ points "
        f"(95\\% CI $[{lo*100:+.2f}, {hi*100:+.2f}]$, $t={t:+.2f}$, $p={p:.4f}$, "
        f"{claim(p)} over the shared seeds).",
        "",
    ]

    if duplicate is not None and nonstyle is not None:
        d_mean = float(np.mean(duplicate))
        n_mean = float(np.mean(nonstyle))
        d1, d1lo, d1hi, d1t, d1p, _ = paired(original, duplicate)
        d2, d2lo, d2hi, d2t, d2p, _ = paired(duplicate, nonstyle)
        d3, d3lo, d3hi, d3t, d3p, _ = paired(nonstyle, adain)
        lines += [
            "\\textit{Where the gain comes from.} The styled groups have twice the "
            "training rows of the Original group, so the headline difference "
            "cannot be attributed to style until the data volume is controlled. "
            "The two control groups do exactly that. ",
            "",
            f"+Duplicate, which adds a byte-identical copy of every training "
            f"image, reaches ${d_mean*100:.1f}\\%$: the pure effect of doubling "
            f"the training rows is ${d1*100:+.2f}$ points "
            f"(95\\% CI $[{d1lo*100:+.2f}, {d1hi*100:+.2f}]$, $p={d1p:.4f}$, "
            f"{claim(d1p)}). ",
            f"+NonStyle, which adds a non-stylistic transform instead, reaches "
            f"${n_mean*100:.1f}\\%$, a further ${d2*100:+.2f}$ points over "
            f"+Duplicate (95\\% CI $[{d2lo*100:+.2f}, {d2hi*100:+.2f}]$, "
            f"$p={d2p:.4f}$, {claim(d2p)}). ",
            f"Style on top of that generic appearance change contributes "
            f"${d3*100:+.2f}$ points (95\\% CI $[{d3lo*100:+.2f}, {d3hi*100:+.2f}]$, "
            f"$p={d3p:.4f}$, {claim(d3p)}). ",
            "",
            "The third row of Table~\\ref{tab:decomposition} is an "
            "\\emph{upper bound}: it contains the comparison of styling against "
            "a generic transform and the comparison of one particular family of "
            "transforms against a random one at the same time, so it is not a "
            "strict causal attribution of style.",
            "",
        ]

    if matched is not None and ours is not None:
        m_mean = float(np.mean(matched))
        ou_mean = float(np.mean(ours))
        d4, d4lo, d4hi, d4t, d4p, _ = paired(matched, ours)
        lines += [
            f"\\textit{{The spatial modulation adds nothing.}} The "
            f"strength-matched control, which receives exactly the same average "
            f"style strength as +Ours but distributes it uniformly, reaches "
            f"${m_mean*100:.1f}\\%$, against ${ou_mean*100:.1f}\\%$ for +Ours: a "
            f"paired difference of ${d4*100:+.2f}$ points "
            f"(95\\% CI $[{d4lo*100:+.2f}, {d4hi*100:+.2f}]$, $t={d4t:+.2f}$, "
            f"$p={d4p:.4f}$, {claim(d4p)}). ",
        ]
        if equal is not None:
            e_mean = float(np.mean(equal))
            d5, d5lo, d5hi, d5t, d5p, _ = paired(adain, equal)
            lines.append(
                f"The equal-strength spatial map confirms the same thing from the "
                f"other side: with the mean strength pinned to 0.500 it reaches "
                f"${e_mean*100:.1f}\\%$ against +AdaIN's "
                f"${a_mean*100:.1f}\\%$, a paired difference of ${d5*100:+.2f}$ "
                f"points (95\\% CI $[{d5lo*100:+.2f}, {d5hi*100:+.2f}]$, "
                f"$p={d5p:.4f}$, {claim(d5p)}). ")
        lines.append("")
        lines.append(
            "Once the average strength is held fixed, the two methods are "
            "indistinguishable: the accuracy of a styled training set is "
            "governed by \\emph{how much} style it applies, not by \\emph{where} "
            "the style is placed.")

    return "\n".join(lines) + "\n"


def build_strength(runs_root: Path) -> str:
    """IV.C: the style-strength relation."""
    lines = [
        "% Generated by member4_training_eval/make_results_text.py -- do not edit by hand.",
        "\\subsection{Style Strength versus Cross-Domain Accuracy}",
        "\\label{sec:strength}",
        "",
        "Figure~\\ref{fig:strength_curve} plots the cross-domain accuracy of "
        "every trained configuration against the average style strength it "
        "applies. The three series are the spatial variant of this project, the "
        "uniform AdaIN variant, and the strength-matched uniform control.",
        "",
    ]

    # The strongest configuration of each series.
    best = {}
    series = common_seeds(runs_root, ("ours", "adain", "adain_matched"))
    for group, values in series.items():
        best[group] = float(np.mean(values))
    if not best:
        return "\n".join(lines) + "\n"

    strength = {"ours": 0.374, "adain": 0.500, "adain_matched": 0.374}
    order = sorted(best, key=lambda g: strength[g])
    text = ", ".join(
        f"{LABELS[g]} at $\\alpha={strength[g]:.3f}$ reaches "
        f"${best[g]*100:.2f}\\%$" for g in order)
    lines += [
        f"Across the main configurations, {text}. The accuracy is therefore a "
        f"function of the average style strength, and the configurations that "
        f"differ in the \\emph{{spatial distribution}} of the strength lie on the "
        f"same curve as the ones that differ in the strength itself.",
        "",
        "The ablation in Section~\\ref{sec:ablation} makes the point directly: "
        "as $\\beta$ increases, the spatial modulation becomes stronger, the "
        "average style strength applied to the images falls accordingly, and "
        "the accuracy follows the strength rather than the modulation.",
        "",
    ]
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--runs-root", type=Path, default=config.OUTPUT_ROOT)
    parser.add_argument("--out-dir", type=Path,
                        default=config.PROJECT_ROOT / "report" / "sections")
    args = parser.parse_args()

    args.out_dir.mkdir(parents=True, exist_ok=True)
    written = []
    for name, builder in (("member4_ivb.tex", build_main_results),
                          ("member4_ivc.tex", build_strength)):
        text = builder(args.runs_root)
        if not text:
            print(f"skipped {name}: the needed summaries are missing")
            continue
        (args.out_dir / name).write_text(text, encoding="utf-8")
        written.append(name)
    print(f"wrote {', '.join(written) if written else 'nothing'}")


if __name__ == "__main__":
    main()
