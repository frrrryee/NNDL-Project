"""Table III: the significance overview of every comparison.

The table reports, for each pair of groups that carries an argument of the
report, the paired mean difference in cross-domain accuracy, its 95%
confidence interval (both the t interval and the percentile-bootstrap
interval), the paired $t$ statistic, the two-sided $p$ value, the
Benjamini--Hochberg corrected $p$ value, the paired Cohen's $d$, and the
conclusion.

The conclusion column is written explicitly, so that a difference that does
not reach significance can never be read as an improvement.

Usage:
    python make_table_iii.py --out ../report/sections/member4_tableiii.tex
"""
from __future__ import annotations

import argparse
import json
import math
from pathlib import Path

import numpy as np
from scipy import stats

import config

CROSS = ("art_painting_test", "cartoon_test", "sketch_test")

#: The comparisons, in reporting order.
PAIRS = (
    ("original", "adain", "style augmentation (data volume not controlled)"),
    ("original", "duplicate", "pure data volume"),
    ("duplicate", "nonstyle", "generic appearance diversity"),
    ("nonstyle", "adain", "style beyond a generic appearance change"),
    ("original", "nonstyle", "appearance change alone"),
    ("adain", "adain_matched", "uniform AdaIN at a lower strength"),
    ("adain_matched", "ours", "spatial modulation at equal mean strength"),
    ("adain", "ours", "spatial modulation, strengths not matched"),
    ("adain", "ours_equal", "spatial modulation vs. uniform at equal strength"),
    ("ours_equal", "adain_matched", "equal-strength spatial vs. matched uniform"),
)

LABELS = {
    "original": "Original",
    "adain": "+AdaIN",
    "adain_matched": "+AdaIN (matched)",
    "ours": "+Ours",
    "ours_equal": "+Ours (equal str.)",
    "duplicate": "+Duplicate",
    "nonstyle": "+NonStyle",
}

BOOTSTRAP_RESAMPLES = 10000
BOOTSTRAP_SEED = 20240601


def load_cross(runs_root: Path, group: str):
    path = runs_root / f"summary_{group}.json"
    if not path.is_file():
        return None
    payload = json.loads(path.read_text(encoding="utf-8"))
    series = []
    for split in CROSS:
        entry = payload.get(split)
        if not entry or not entry.get("per_seed"):
            return None
        series.append(entry["per_seed"])
    seeds = min(len(s) for s in series)
    return [float(np.mean([s[i] for s in series])) for i in range(seeds)]


def bootstrap_ci(diff: np.ndarray) -> tuple:
    n = len(diff)
    if n < 2:
        return None
    rng = np.random.default_rng(BOOTSTRAP_SEED)
    means = rng.choice(diff, size=(BOOTSTRAP_RESAMPLES, n), replace=True).mean(axis=1)
    return float(np.percentile(means, 2.5)), float(np.percentile(means, 97.5))


def benjamini_hochberg(p_values: list) -> list:
    n = len(p_values)
    if n == 0:
        return []
    order = sorted(range(n), key=lambda i: p_values[i])
    adjusted = [0.0] * n
    previous = 1.0
    for rank, index in enumerate(reversed(order), start=1):
        value = p_values[index] * n / (n - rank + 1)
        previous = min(previous, value)
        adjusted[index] = min(1.0, previous)
    return adjusted


def common_seeds(runs_root: Path, groups: tuple) -> dict:
    """The per-seed cross-domain averages, restricted to the shared seeds.

    While the seed extension is still running, some groups have five seeds
    and others three.  A paired comparison is only valid over the seeds the
    two groups have in common, so the series are truncated to the common
    prefix.
    """
    raw = {g: load_cross(runs_root, g) for g in groups}
    raw = {g: v for g, v in raw.items() if v is not None}
    if not raw:
        return {}
    length = min(len(v) for v in raw.values())
    return {g: v[:length] for g, v in raw.items()}


def compare(a: list, b: list) -> dict:
    x = np.asarray(a, dtype=float)
    y = np.asarray(b, dtype=float)
    diff = y - x
    n = len(diff)
    mean = float(diff.mean())
    sd = float(diff.std(ddof=1)) if n > 1 else 0.0
    if n > 1 and sd > 0:
        t, p = stats.ttest_rel(y, x)
        t, p = float(t), float(p)
        half = stats.t.ppf(0.975, n - 1) * sd / math.sqrt(n)
    else:
        t, p, half = (0.0, 1.0), 1.0, 0.0
    boot = bootstrap_ci(diff)
    d = mean / sd if sd > 0 else 0.0
    return {"n": n, "mean": mean, "lo": mean - half, "hi": mean + half,
            "boot": boot, "t": t, "p": p, "d": d}


def latex(results: list, n_seeds: int) -> str:
    crit = stats.t.ppf(0.975, max(n_seeds - 1, 1))
    lines = [
        "% Generated by member4_training_eval/make_table_iii.py -- do not edit by hand.",
        "\\begin{table*}[t]",
        "\\centering",
        f"\\caption{{Significance overview. Every comparison is paired over the "
        f"{n_seeds} shared seeds; the difference is the second group minus the "
        f"first, in percentage points of the cross-domain average.  The "
        f"$t$ interval assumes normality while the bootstrap interval does "
        f"not, so the latter is the more trustworthy one at this sample size.  "
        f"$p_{{FDR}}$ is the Benjamini--Hochberg corrected $p$ value over all "
        f"the comparisons in the table.  At $n = {n_seeds}$ the critical value "
        f"is $|t| > {crit:.3f}$.}}",
        "\\label{tab:significance}",
        "\\scriptsize",
        "\\setlength{\\tabcolsep}{3.4pt}",
        "\\begin{tabular}{@{}llrrrcrrl@{}}",
        "\\toprule",
        "Comparison & Interpretation & $\\Delta$ & 95\\% CI (bootstrap) & $t$ & "
        "$p$ & $p_{\\mathrm{FDR}}$ & $d$ & Conclusion \\\\",
        "\\midrule",
    ]
    for row in results:
        boot = row["boot"]
        boot_text = (f"[{boot[0]*100:+.2f}, {boot[1]*100:+.2f}]" if boot else "--")
        if row["p_fdr"] < 0.05:
            conclusion = "significant"
        elif row["p"] < 0.05:
            conclusion = "n.s. after FDR"
        else:
            conclusion = "not significant"
        lines.append(
            f"{LABELS.get(row['a'], row['a'])} $\\rightarrow$ {LABELS.get(row['b'], row['b'])} & "
            f"{row['note']} & ${row['mean']*100:+.2f}$ & {boot_text} & "
            f"${row['t']:+.2f}$ & ${row['p']:.4f}$ & ${row['p_fdr']:.4f}$ & "
            f"${row['d']:+.2f}$ & {conclusion} \\\\")
    lines += [
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table*}",
    ]
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--runs-root", type=Path, default=config.OUTPUT_ROOT)
    parser.add_argument("--out", type=Path,
                        default=config.PROJECT_ROOT / "report" / "sections" / "member4_tableiii.tex")
    parser.add_argument("--json-out", type=Path, default=None,
                        help="write the full comparison record as JSON")
    args = parser.parse_args()

    results = []
    all_groups = tuple(sorted({g for pair in PAIRS for g in pair[:2]}))
    series = common_seeds(args.runs_root, all_groups)
    for group_a, group_b, note in PAIRS:
        if group_a not in series or group_b not in series:
            continue
        row = compare(series[group_a], series[group_b])
        row.update({"a": group_a, "b": group_b, "note": note})
        results.append(row)
    if not results:
        print("no comparable groups found; run the experiments first")
        return

    p_values = [r["p"] for r in results if math.isfinite(r["p"])]
    adjusted = benjamini_hochberg(p_values)
    index = 0
    for row in results:
        if math.isfinite(row["p"]):
            row["p_fdr"] = adjusted[index]
            index += 1
        else:
            row["p_fdr"] = 1.0

    n_seeds = max(r["n"] for r in results)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(latex(results, n_seeds), encoding="utf-8")
    print(f"wrote {args.out}")
    if args.json_out:
        args.json_out.write_text(json.dumps(results, indent=2), encoding="utf-8")
        print(f"wrote {args.json_out}")


if __name__ == "__main__":
    main()
