"""Generate the LaTeX fragments of the structural-mechanism analysis.

One fragment is written:

    report/sections/member4_edgeclass.tex   the per-class edge retention
                                             table and the mechanism test

The numbers come from the cached per-image EdgeScores
(``runs/edge_analysis.npz``), which are produced by
``structure_mechanism.py``.  Nothing is recomputed here, so the table and
the mechanism test cannot disagree with each other: both are read from the
same per-image arrays.

Usage:
    python make_edge_table.py
"""
from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
from scipy import stats

import config


def load(runs_root: Path):
    path = runs_root / "edge_analysis.npz"
    if not path.is_file():
        return None
    payload = np.load(path)
    return (payload["ours"], payload["adain"], payload["matched"],
            payload["labels"], payload["density"])


def build(ours, adain, matched, labels, density) -> str:
    """The per-class table and the mechanism test, as one LaTeX fragment."""
    lines = [
        "% Generated by member4_training_eval/make_edge_table.py "
        "-- do not edit by hand.",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{Edge retention per class. ``Edge'' is the EdgeScore of "
        "Section~\\ref{sec:structure}: the F1 overlap between the binary edge "
        "map of the generated image and that of the source image.  The three "
        "sets share the content images, the style references and the pairing, "
        "and differ only in the rule that computes the blending weight; "
        "``+Match'' is the uniform control whose mean strength equals that of "
        "``+Ours''.  ``Density'' is the number of edges in the content image.  "
        "The last column is the paired difference ``+Ours $-$ +Match'' over "
        "the images of the class.}",
        "\\label{tab:edgeclass}",
        "\\centering",
        "\\scriptsize",
        "\\setlength{\\tabcolsep}{4pt}",
        "\\begin{tabular}{@{}lrrrrrr@{}}",
        "\\toprule",
        "Class & $n$ & Density & +AdaIN & +Match & +Ours & Ours$-$Match \\\\",
        "\\midrule",
    ]

    gain = ours - matched
    valid = ~np.isnan(gain)
    for index, name in enumerate(config.CLASSES):
        mask = labels == index
        if not mask.any():
            continue
        _t, p = stats.ttest_rel(ours[mask], matched[mask])
        # The dagger marks a significant difference.  It has to be *inside*
        # the math mode of the number, so it is appended to the value and
        # the whole cell is wrapped in a single pair of dollar signs.
        marker = "" if p >= 0.05 else "^{\\dagger}"
        lines.append(
            f"{name} & {int(mask.sum())} & {density[mask].mean():.0f} & "
            f"{adain[mask].mean():.4f} & {matched[mask].mean():.4f} & "
            f"{ours[mask].mean():.4f} & ${gain[mask].mean():+.4f}{marker}$ \\\\")

    # The mechanism test: does the gain grow with the structural density?
    r, pr = stats.pearsonr(density[valid], gain[valid])
    rho, prho = stats.spearmanr(density[valid], gain[valid])
    median = float(np.median(density[valid]))
    low = valid & (density <= median)
    high = valid & (density > median)
    t, pw = stats.ttest_ind(gain[high], gain[low], equal_var=False)

    lines += [
        "\\midrule",
        f"All & {int(valid.sum())} & {density[valid].mean():.0f} & "
        f"{adain[valid].mean():.4f} & {matched[valid].mean():.4f} & "
        f"{ours[valid].mean():.4f} & ${gain[valid].mean():+.4f}$ \\\\",
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table}",
        "",
        "% The mechanism test, as prose.  If the modulation preserved "
        "structure for its stated reason, the high-density half must gain "
        "more than the low-density half.",
        f"\\noindent\\textbf{{Mechanism test.}} Splitting the images at the "
        f"median structural density ({median:.0f} edges), the high-density "
        f"half gains ${gain[high].mean():+.4f} \\pm {gain[high].std(ddof=1):.4f}$ "
        f"($n={int(high.sum())}$) and the low-density half "
        f"${gain[low].mean():+.4f} \\pm {gain[low].std(ddof=1):.4f}$ "
        f"($n={int(low.sum())}$): Welch $t={t:+.2f}$, $p={pw:.3f}$.  The "
        f"correlation between an image's structural density and its gain is "
        f"negligible (Pearson $r={r:+.3f}$, $p={pr:.3f}$; Spearman "
        f"$\\rho={rho:+.3f}$, $p={prho:.4f}$).  The modulation therefore does "
        f"\\emph{{not}} buy extra edge retention where the structure is "
        f"strongest.",
    ]
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--runs-root", type=Path, default=config.OUTPUT_ROOT)
    parser.add_argument("--out", type=Path,
                        default=config.PROJECT_ROOT / "report" / "sections" /
                        "member4_edgeclass.tex")
    args = parser.parse_args()

    payload = load(args.runs_root)
    if payload is None:
        print(f"{args.runs_root}/edge_analysis.npz is missing; "
              f"run structure_mechanism.py first")
        return
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(build(*payload), encoding="utf-8")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
