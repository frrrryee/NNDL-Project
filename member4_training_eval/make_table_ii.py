"""Table II: the main results table, generated from the recorded summaries.

The table has one row per experimental group and one column per evaluation
domain, plus the cross-domain average.  Every entry is mean$\\pm$standard
deviation over the seeds of that group.

The table is generated rather than typed, because the report requires that
every number in it can be recomputed from ``runs/``.  The table also records
the number of seeds in its caption, so that a reader can see at once how
much evidence stands behind each cell.

Usage:
    python make_table_ii.py --out ../report/sections/member4_tableii.tex
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

import config

SPLITS = ("photo_test", "art_painting_test", "cartoon_test", "sketch_test")

GROUP_ORDER = ("original", "duplicate", "nonstyle", "adain", "adain_matched",
               "ours", "ours_equal", "mixstyle")

LABELS = {
    "original": "Original",
    "duplicate": "+Duplicate",
    "nonstyle": "+NonStyle",
    "adain": "+AdaIN",
    "adain_matched": "+AdaIN (matched)",
    "ours": "+Ours",
    "ours_equal": "+Ours (equal str.)",
    "mixstyle": "MixStyle",
}

#: The groups whose row is set in bold: the two that reach the highest
#: cross-domain average.
BOLD = ("adain", "ours_equal")


def load(runs_root: Path, group: str):
    path = runs_root / f"summary_{group}.json"
    if not path.is_file():
        return None
    payload = json.loads(path.read_text(encoding="utf-8"))
    if not all(split in payload for split in SPLITS):
        return None
    return payload


def cell(payload: dict, split: str) -> str:
    entry = payload.get(split)
    if not entry:
        return "--"
    return f"${entry['mean']*100:.1f}\\pm{entry['std']*100:.1f}$"


def cross_cell(payload: dict) -> str:
    """The cross-domain average and its spread *over the seeds*.

    The average is the mean of the three target-domain accuracies, and the
    spread is the standard deviation of that average over the seeds.  The
    standard deviation of the three domain means would describe the spread
    *between* the domains, which is a different quantity and would make the
    column look alarmingly large.
    """
    per_seed = []
    seeds = None
    for split in SPLITS[1:]:
        entry = payload.get(split)
        if not entry or not entry.get("per_seed"):
            return "--"
        series = entry["per_seed"]
        seeds = len(series) if seeds is None else min(seeds, len(series))
        per_seed.append(series)
    averages = [sum(s[i] for s in per_seed) / len(per_seed) for i in range(seeds)]
    mean = sum(averages) / len(averages)
    std = (sum((v - mean) ** 2 for v in averages) / (len(averages) - 1)) ** 0.5 \
        if len(averages) > 1 else 0.0
    return f"${mean*100:.1f}\\pm{std*100:.1f}$"


def latex(rows: list, n_seeds: int) -> str:
    lines = [
        "% Generated by member4_training_eval/make_table_ii.py -- do not edit by hand.",
        "\\begin{table}[t]",
        "\\centering",
        f"\\caption{{Main results. Entries are mean$\\pm$standard deviation over "
        f"{n_seeds} seeds, reported for the final checkpoint of the fixed "
        f"660-step budget.  ``CrossAvg'' is the unweighted average of the "
        f"three target domains.  +Duplicate and +NonStyle are the "
        f"data-volume controls: they have the same number of training rows as "
        f"the styled groups, but +Duplicate's extra images are byte-identical "
        f"copies and +NonStyle's are non-stylistic transforms.  MixStyle is a "
        f"published feature-space baseline with a different architecture, so "
        f"it trains on the original images and carries its own "
        f"configuration fingerprint.}}",
        "\\label{tab:main_results}",
        "\\centering",
        "\\scriptsize",
        "\\setlength{\\tabcolsep}{2.6pt}",
        "\\begin{tabular}{@{}lccccc@{}}",
        "\\toprule",
        "Training method & Photo & Art & Cartoon & Sketch & CrossAvg \\\\",
        "\\midrule",
    ]
    for group, payload in rows:
        label = LABELS.get(group, group)
        if group in BOLD:
            label = f"\\textbf{{{label}}}"
        lines.append(
            f"{label} & {cell(payload, 'photo_test')} & "
            f"{cell(payload, 'art_painting_test')} & {cell(payload, 'cartoon_test')} & "
            f"{cell(payload, 'sketch_test')} & {cross_cell(payload)} \\\\")
    lines += [
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table}",
    ]
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--runs-root", type=Path, default=config.OUTPUT_ROOT)
    parser.add_argument("--out", type=Path,
                        default=config.PROJECT_ROOT / "report" / "sections" / "member4_tableii.tex")
    args = parser.parse_args()

    rows = []
    n_seeds = 0
    for group in GROUP_ORDER:
        payload = load(args.runs_root, group)
        if payload is None:
            continue
        rows.append((group, payload))
        n_seeds = max(n_seeds, len(payload.get("seeds", [])))
    if not rows:
        print("no summaries found; run the experiments first")
        return
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(latex(rows, n_seeds), encoding="utf-8")
    print(f"wrote {args.out}  ({len(rows)} groups, {n_seeds} seeds)")


if __name__ == "__main__":
    main()
