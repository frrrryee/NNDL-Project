"""Copy the recorded run results into the repository, without the machine.

The runs directory is the working area: it holds a checkpoint beside
every result, and the checkpoint is far too large to commit.  What the
repository needs is the result itself, so that a reader can check a
number in the report against the file it came from without asking for
the training run.

This script copies the JSON results and rewrites the paths they carry.
The paths are absolute on the machine that produced the run, which
ties them to one person's directory layout; they are made relative to
the data root instead, which is what the rest of the repository does.

The checkpoints are not copied.  They are regenerated by ``train.py``
from the recorded configuration, and the ``config_hash`` in each
summary identifies which configuration that was.

Usage:
    python export_run_results.py
    python export_run_results.py --dry-run
"""
from __future__ import annotations

import argparse
import json
import re
import shutil
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent
import sys

sys.path.insert(0, str(HERE))
sys.path.insert(0, str(REPO))

import config  # noqa: E402

RUNS = config.OUTPUT_ROOT
DESTINATION = REPO / "results" / "runs"

#: The run directories that are not part of a reported group: the
#: diagnostics and the budget probes, which have no result to report.
SKIP = ("diag_", "_archive")


def relative(path: str) -> str:
    """A path that does not name the machine that produced it."""
    text = path.replace("\\", "/")
    for root in (str(config.DATA_ROOT), str(RUNS), str(REPO)):
        root = root.replace("\\", "/").rstrip("/")
        if root and text.lower().startswith(root.lower()):
            return text[len(root):].lstrip("/")
    # A path that names some other absolute root is reduced to its last
    # two components, which is enough to identify the file.
    parts = [p for p in text.split("/") if p]
    if len(parts) > 2 and re.match(r"^[A-Za-z]:", parts[0]):
        return "/".join(parts[-2:])
    return text


def sanitize(node):
    """Every string in the tree that looks like a path is made relative."""
    if isinstance(node, str):
        if re.match(r"^[A-Za-z]:[\\/]", node) or node.startswith("\\\\"):
            return relative(node)
        return node
    if isinstance(node, list):
        return [sanitize(item) for item in node]
    if isinstance(node, dict):
        return {key: sanitize(value) for key, value in node.items()}
    return node


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()

    if not RUNS.is_dir():
        print(f"  no runs directory at {RUNS}")
        return 1

    copied = skipped = 0
    for source in sorted(RUNS.rglob("*.json")):
        if source.suffix != ".json":
            continue
        relative_source = source.relative_to(RUNS)
        if any(part.startswith(SKIP) for part in relative_source.parts):
            skipped += 1
            continue

        target = DESTINATION / relative_source
        try:
            payload = json.loads(source.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            skipped += 1
            continue

        cleaned = json.dumps(sanitize(payload), indent=2, ensure_ascii=False)
        if args.dry_run:
            print(f"  would copy {relative_source}")
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(cleaned + "\n", encoding="utf-8")
        copied += 1

    print()
    print(f"  {copied} result files, {skipped} skipped")
    print(f"  destination: {DESTINATION}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
